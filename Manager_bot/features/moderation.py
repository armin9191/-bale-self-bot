# ==============================
# تشخیص دستور
# ==============================

def detect_command(text):

    if not text:
        return None

    text = text.strip().lower()

    for command, aliases in COMMANDS.items():

        if text in aliases:
            return command

    return None


# ==============================
# پردازش دستور
# ==============================

def handle_message(message):

    if not message:
        return False

    text = message.get("text", "")

    command = detect_command(text)

    if not command:
        return False

    # ==========================
    # فعلاً فقط تشخیص
    # ==========================

    return {
        "command": command,
        "message": message
    }
